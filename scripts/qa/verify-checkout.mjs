import { spawnSync } from 'node:child_process';
import { createQaDirectory } from '../lib/qa-directory.mjs';
import electron from 'electron';
const directory = createQaDirectory('checkout');
const env = { ...process.env };
for(const key of Object.keys(env))if(key.startsWith('FOX_VERIFY_'))delete env[key];
env.FOX_VERIFY_DIR=directory;env.FOX_VERIFY_CHECKOUT='1';
for(const key of ['ELECTRON_RUN_AS_NODE','FOX_DEV_URL','FOX_VERIFY_MANUAL','FOX_VERIFY_ORDER_RESTART','FOX_VERIFY_CHECKOUT_RESTART'])delete env[key];
let result = spawnSync(electron, ['--force-device-scale-factor=1','.'], { stdio: 'inherit', env, timeout: 120000, windowsHide: true });
if(result.status===0)result=spawnSync(electron,['--force-device-scale-factor=1','.'],{stdio:'inherit',env:{...env,FOX_VERIFY_CHECKOUT_RESTART:'1'},timeout:120000,windowsHide:true});
if(result.error)console.error(result.error);
console.log(`Isolated checkout verification files: ${directory}`);
process.exitCode = result.status ?? 1;
