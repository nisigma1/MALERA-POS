import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import electron from 'electron';
import {createQaDirectory} from './qa-directory.mjs';
const target=JSON.parse(fs.readFileSync(process.argv[2]||'work/printer-qa-target.json','utf8'));
const directory=createQaDirectory('receipts');
const env={...process.env};for(const key of Object.keys(env))if(key.startsWith('FOX_VERIFY_')||['ELECTRON_RUN_AS_NODE','FOX_DEV_URL'].includes(key))delete env[key];
Object.assign(env,{FOX_VERIFY_DIR:directory,FOX_VERIFY_RECEIPTS:'1',FOX_VERIFY_PRINTER:target.Printer,FOX_VERIFY_PRINTER_OUTPUT:target.Port});
const result=spawnSync(electron,['--force-device-scale-factor=1','.'],{env,windowsHide:true,stdio:'inherit',timeout:180000});
console.log('Receipt verification evidence: '+directory);if(result.error)console.error(result.error);process.exitCode=result.status??1;
